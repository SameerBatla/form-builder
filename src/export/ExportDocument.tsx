import { formatDateTime } from '../lib/dates'
import type { ExportItem, ExportModel } from './buildExportModel'

// The form title is the document's h1, so sections use h2 (XL) to h6 (XS).
const headingTags = { xl: 'h2', lg: 'h3', md: 'h4', sm: 'h5', xs: 'h6' } as const

function ExportRow({ item }: { item: ExportItem }) {
  if (item.kind === 'heading') {
    const Heading = headingTags[item.size]
    return (
      <Heading className={`fb-export__heading fb-export__heading--${item.size}`}>
        {item.text}
      </Heading>
    )
  }
  return (
    <div className="fb-export__row">
      <div className="fb-export__label">{item.label}</div>
      <div className="fb-export__value">
        {item.lines.length === 0 ? (
          <span className="fb-export__empty">—</span>
        ) : (
          item.lines.map((line, index) => <p key={index}>{line}</p>)
        )}
        {item.note && item.lines.length > 0 && (
          <p className="fb-export__note">{item.note}</p>
        )}
      </div>
    </div>
  )
}

/**
 * The document view of a response: a real export, not the form UI. Rendered in
 * the app (response view) and to static HTML for printing to PDF.
 */
export default function ExportDocument({ model }: { model: ExportModel }) {
  return (
    <article className="fb-export">
      <header className="fb-export__header">
        <p className="fb-export__eyebrow">Response {model.responseNumber}</p>
        <h1 className="fb-export__title">{model.title}</h1>
        <p className="fb-export__meta">
          Submitted{' '}
          <time dateTime={model.submittedAt}>{formatDateTime(model.submittedAt)}</time>
        </p>
      </header>
      {model.items.map((item) => (
        <ExportRow key={item.id} item={item} />
      ))}
      <footer className="fb-export__footer">Generated by Form Builder</footer>
    </article>
  )
}
